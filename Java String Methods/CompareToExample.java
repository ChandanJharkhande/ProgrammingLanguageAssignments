public class CompareToExample {
    public static void main(String[] args) {
        String s1 = "Apple";
        String s2 = "Apple";
        String s3 = "Banana";
        String s4 = "Ant";

        System.out.println(s1.compareTo(s2));
        System.out.println(s1.compareTo(s3));
        System.out.println(s1.compareTo(s4));
    }
}
